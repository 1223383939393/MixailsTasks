#pragma once
#include <iostream>
using namespace std;

// Это базовый класс для всех геометрических фигур
// "абстрактный класс" — его нельзя создать сам по себе,
// зато от него можно наследоваться (Circle, Rectangle, Triangle).
class Shape
{
public:
    // Виртуальная функция для вычисления площади фигуры.
    // В Shape мы её не реализуем, она ЧИСТО ВИРТУАЛЬНАЯ —
    // поэтому у всех наследников обязательно будет свой area().
    virtual double area() const = 0;

    // Виртуальная функция для вычисления периметра фигуры.
    // Тоже чисто виртуальная — каждый наследник сам считает свой периметр.
    virtual double perimeter() const = 0;

    // Виртуальная функция для вывода информации о фигуре на экран.
    // Каждый наследник сам напечатает свои данные (например, радиус, сторону…).
    virtual void print() const = 0;

    // Виртуальный деструктор.
    // Нужен, чтобы при удалении объекта через Shape* вызывался правильный деструктор Circle/Rectangle/Triangle.
    virtual ~Shape() {}

    // Статический счётчик: сколько фигур ВСЕГО создано (общий для всех фигур).
    // Каждый раз, когда создается Circle/Rectangle/Triangle, в их конструкторах делается count++.
    static int count;
};

// Круг — производный класс от Shape.
class Circle : public Shape {
private:
    // Радиус круга.
    int radius;

    // Число Пи, которое будет использоваться в формулах площади и периметра.
    const double pi = 3.14;

public:
    // Конструктор: создаёт круг с заданным радиусом r.
    // Внутри тела конструктора увеличиваем общий счётчик фигур count.
    Circle(int r) : radius{ r } { count++; }

    // Переопределённый метод для вычисления периметра круга (объявление).
    // В .cpp будет реализация: P = 2 * π * radius.
    double perimeter() const override;

    // Переопределённый метод для вычисления площади круга (объявление).
    // В .cpp будет реализация: S = π * radius * radius.
    double area() const override;

    // Переопределённый метод для вывода информации о круге на экран.
    // Выводит только радиус.
    void print() const override {
        cout << "Radius= " << radius << endl;
    }
};

// Квадрат — производный класс от Shape (в коде назван Rectangle).
class Rectangle : public Shape {
private:
    // Длина стороны квадрата (a).
    int a;

public:
    // Конструктор: создаёт квадрат с одной стороной a.
    // Внутри увеличиваем общий счётчик фигур count.
    Rectangle(int a) : a{ a } { count++; }

    // Переопределённый метод для вычисления периметра квадрата (объявление).
    // В .cpp будет: P = 4 * a.
    double perimeter() const override;

    // Переопределённый метод для вычисления площади квадрата (объявление).
    // В .cpp будет: S = a * a.
    double area() const override;

    // Переопределённый метод для вывода информации о квадрате на экран.
    // Выводит одну сторону (хотя в квадрате все стороны равны).
    void print() const override {
        cout << "Side= " << a << endl;
    }
};

// Треугольник — производный класс от Shape.
class Triangle : public Shape {
private:
    // Три стороны треугольника: a, b, c.
    // Высота h — к стороне a (основанию).
    int a, b, c, h;

public:
    // Конструктор: создаёт треугольник с тремя сторонами и высотой.
    // Внутри увеличиваем общий счётчик фигур count.
    Triangle(int a, int b, int c, int h) : a{ a }, b{ b }, c{ c }, h{ h } { count++; }

    // Переопределённый метод для вычисления периметра треугольника (объявление).
    // В .cpp будет: P = a + b + c.
    double perimeter() const override;

    // Переопределённый метод для вычисления площади треугольника (объявление).
    // В .cpp будет: S = 0.5 * a * h (формула: половина основания на высоту).
    double area() const override;

    // Переопределённый метод для вывода информации о треугольнике.
    // Выводит три стороны, не высоту (высота нужна только для вычисления площади).
    void print() const override {
        cout << "Side 1 = " << a << ", Side 2 = " << b << ", Side 3 = " << c << endl;
    }
};
