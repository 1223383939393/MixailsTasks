#pragma once                     // Гарантирует, что этот заголовочный файл подключится только один раз

#include <iostream>              // Библиотека для ввода/вывода (cout, cin)
using namespace std;             // Чтобы каждый раз не писать std:: перед cout и другими сущностями

class Matrix
{
    int X, Y;                    // Переменные для размеров (в этом коде не используются, но объявлены)
    int matrix[3][3];            // Внутреннее хранилище элементов матрицы 3x3

public:
    Matrix();                    // Конструктор по умолчанию: создаёт матрицу и заполняет её нулями
    Matrix(const int m[3][3]);   // Конструктор, принимающий готовый массив 3x3 и копирующий его в matrix

    // Оператор сложения матриц: складывает поэлементно текущую матрицу и ot, возвращает новую матрицу
    Matrix operator +(const Matrix& ot);

    // Оператор вычитания матриц: вычитает поэлементно ot из текущей матрицы, возвращает новую матрицу
    Matrix operator -(const Matrix& ot);

    // Оператор умножения матриц (здесь реализован поэлементно: элементы перемножаются друг с другом)
    Matrix operator *(const Matrix& ot);

    // Оператор умножения матрицы на целое число: каждый элемент умножается на скаляр k
    Matrix operator *(int k);

    // Оператор доступа к элементу по индексу (x, y) для константного объекта
    // Возвращает константную ссылку на элемент matrix[x][y]
    const int& operator ()(int x, int y) const;

    // Оператор логического НЕ (!) переопределён как транспонирование матрицы
    // Возвращает новую матрицу, где строки и столбцы поменяны местами
    Matrix operator !();

    // Оператор присваивания: копирует все элементы из матрицы ot в текущую матрицу
    Matrix operator =(const Matrix& ot);

    // Оператор сравнения на равенство: возвращает true, если все 9 элементов матриц совпадают
    bool operator ==(const Matrix& ot);
};