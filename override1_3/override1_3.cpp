#include <iostream>              // Библиотека для ввода/вывода (cout, endl)
#include "Matrix.h"              // Заголовок с определением класса Matrix

using namespace std;             // Чтобы не писать std:: перед cout и endl

int main() {
    // Исходные данные для первой матрицы A (3x3)
    int aData[3][3] = {
        {1, 2, 3},               // Первая строка матрицы A
        {4, 5, 6},               // Вторая строка матрицы A
        {7, 8, 9}                // Третья строка матрицы A
    };

    // Исходные данные для второй матрицы B (3x3)
    int bData[3][3] = {
        {9, 8, 7},               // Первая строка матрицы B
        {6, 5, 4},               // Вторая строка матрицы B
        {3, 2, 1}                // Третья строка матрицы B
    };

    // Создаём матрицы A и B, инициализируя их из массивов aData и bData
    Matrix A(aData);             // Конструктор копирует значения из aData в A.matrix
    Matrix B(bData);             // Конструктор копирует значения из bData в B.matrix

    // Проверяем оператор сравнения ==
    bool eq = (A == B);          // Сравниваем A и B по всем 9 элементам
    cout << "A == B: " << eq << endl;  // Выводим результат сравнения (0 или 1)

    // Проверяем оператор сложения +
    Matrix C1 = A + B;           // C1 содержит поэлементную сумму матриц A и B

    // Проверяем оператор вычитания -
    Matrix C2 = A - B;           // C2 содержит поэлементную разницу A и B

    // Проверяем оператор поэлементного умножения матриц *
    Matrix C3 = A * B;           // C3 содержит поэлементное произведение A и B

    // Проверяем оператор умножения матрицы на скаляр
    Matrix C4 = A * 2;           // C4 содержит матрицу A, умноженную на число 2

    // Проверяем оператор транспонирования ! для матрицы A
    Matrix AT = !A;              // AT — транспонированная версия матрицы A

    // Проверяем оператор присваивания =
    Matrix D;                    // Создаём новую матрицу D (по умолчанию заполнена нулями)
    D = A;                       // Копируем в D все элементы матрицы A

    // Пример использования оператора () для доступа к элементу
    cout << "A(0,0) = " << A(0, 0) << endl;  // Читаем верхний левый элемент матрицы A

    cout << "Program finished, all operators have been called." << endl; // Сообщаем о завершении

    return 0;                    // Возвращаем 0 — успешное завершение программы
}