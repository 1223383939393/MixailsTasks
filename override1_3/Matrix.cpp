#include "Matrix.h"              // Подключаем заголовок с объявлением класса Matrix

// Конструктор по умолчанию: создаёт матрицу 3x3 и заполняет все элементы нулями
Matrix::Matrix() {
    // Два вложенных цикла проходят по всей матрице
    for (int i = 0; i < 3; ++i)          // Цикл по строкам
        for (int j = 0; j < 3; ++j)      // Цикл по столбцам
            matrix[i][j] = 0;            // Устанавливаем каждый элемент в 0
}

// Конструктор, принимающий внешний массив 3x3 и копирующий его в поле matrix
Matrix::Matrix(const int m[3][3]) {
    // Два вложенных цикла копируют элементы из m в matrix
    for (int i = 0; i < 3; ++i)          // Цикл по строкам
        for (int j = 0; j < 3; ++j)      // Цикл по столбцам
            matrix[i][j] = m[i][j];      // Копируем значение из m[i][j] в matrix[i][j]
}

// Оператор сложения матриц: поэлементно складывает this и ot, возвращает результат
Matrix Matrix::operator +(const Matrix& ot) {
    Matrix res;                          // Локальная матрица-результат, в неё будут записаны суммы

    // Проходим по всем индексам 3x3
    for (int i = 0; i < 3; i++) {        // Цикл по строкам
        for (int j = 0; j < 3; j++) {    // Цикл по столбцам
            // Складываем соответствующие элементы двух матриц и записываем в res
            res.matrix[i][j] = matrix[i][j] + ot.matrix[i][j];
        }
    }
    return res;                          // Возвращаем полученную матрицу
}

// Оператор вычитания матриц: поэлементно вычитает ot из текущей матрицы
Matrix Matrix::operator -(const Matrix& ot) {
    Matrix res;                          // Локальная матрица-результат для разности

    // Проходим по всем элементам 3x3
    for (int i = 0; i < 3; i++) {        // Цикл по строкам
        for (int j = 0; j < 3; j++) {    // Цикл по столбцам
            // Вычитаем соответствующие элементы и сохраняем в res
            res.matrix[i][j] = matrix[i][j] - ot.matrix[i][j];
        }
    }
    return res;                          // Возвращаем матрицу с результатом вычитания
}

// Оператор умножения матриц (в текущем коде — поэлементное умножение)
Matrix Matrix::operator *(const Matrix& ot) {
    Matrix res;                          // Локальная матрица-результат для произведения

    // Проходим по всем позициям 3x3
    for (int i = 0; i < 3; i++) {        // Цикл по строкам
        for (int j = 0; j < 3; j++) {    // Цикл по столбцам
            // Перемножаем элементы на одинаковых позициях и записываем в res
            res.matrix[i][j] = matrix[i][j] * ot.matrix[i][j];
        }
    }
    return res;                          // Возвращаем поэлементное произведение матриц
}

// Оператор умножения матрицы на целое число k
Matrix Matrix::operator*(int k) {
    Matrix res;                          // Локальная матрица-результат для умножения на скаляр

    // Проходим по всем элементам 3x3
    for (int i = 0; i < 3; ++i) {        // Цикл по строкам
        for (int j = 0; j < 3; ++j) {    // Цикл по столбцам
            // Каждый элемент умножаем на k и записываем в res
            res.matrix[i][j] = k * matrix[i][j];
        }
    }
    return res;                          // Возвращаем матрицу, умноженную на скаляр
}

// Оператор () — доступ к элементу (x, y) для константного объекта
const int& Matrix::operator ()(int x, int y) const {
    // Возвращаем константную ссылку на элемент matrix[x][y],
    // это позволяет читать значение элемента без копирования
    return matrix[x][y];
}

// Оператор ! — реализует транспонирование матрицы
Matrix Matrix::operator!() {
    Matrix res;                          // Локальная матрица-результат для транспонированной матрицы

    // Проходим по всем индексам 3x3
    for (int i = 0; i < 3; ++i) {        // Цикл по строкам исходной матрицы
        for (int j = 0; j < 3; ++j) {    // Цикл по столбцам исходной матрицы
            // Переписываем элемент [i][j] текущей матрицы в позицию [j][i] резульата
            res.matrix[j][i] = matrix[i][j];
        }
    }
    return res;                          // Возвращаем транспонированную матрицу
}

// Оператор присваивания: копирует элементы из ot в текущую матрицу
Matrix Matrix::operator =(const Matrix& ot) {
    // Проверка на самоприсваивание: если объект присваивают сам себе, делать ничего не нужно
    if (this == &ot) {
        return *this;                    // Возвращаем текущий объект без изменений
    }

    // Копируем все элементы 3x3 из ot.matrix в matrix
    for (int i = 0; i < 3; ++i) {        // Цикл по строкам
        for (int j = 0; j < 3; ++j) {    // Цикл по столбцам
            matrix[i][j] = ot.matrix[i][j]; // Копируем значение элемента
        }
    }
    return *this;                        // Возвращаем текущий объект после присваивания
}

// Оператор сравнения на равенство: проверяет, совпадают ли все 9 элементов матриц
bool Matrix::operator ==(const Matrix& ot) {
    int res = 0;                         // Счётчик совпавших элементов (изначально 0)
    int mat[3][3];                       // Локальный массив (в этом коде не используется, просто объявлен)

    // Проходим по всем элементам 3x3
    for (int i = 0; i < 3; i++) {        // Цикл по строкам
        for (int j = 0; j < 3; j++) {    // Цикл по столбцам
            // Если элементы текущей матрицы и ot совпадают
            if (matrix[i][j] == ot.matrix[i][j]) {
                res++;                   // Увеличиваем счётчик совпадений
            }
        }
    }

    if (res == 9) {                      // Если совпало ровно 9 элементов (вся матрица 3x3)
        return true;                     // Матрицы считаются равными
    }
    else {
        return false;                    // Если хоть один элемент отличается, матрицы не равны
    }
}